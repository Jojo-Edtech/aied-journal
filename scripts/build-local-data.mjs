import { readFile, writeFile, mkdir } from "node:fs/promises";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const root = fileURLToPath(new URL("../", import.meta.url));
const jsonLiteral = (value) => JSON.stringify(JSON.stringify(value))
  .replaceAll("<", "\\u003c").replaceAll("\u2028", "\\u2028").replaceAll("\u2029", "\\u2029");

export async function buildLocalData({ projectRoot = root, quiet = false } = {}) {
  const loader = await readFile(resolve(projectRoot, "data-loader.js"), "utf8");
  const context = vm.createContext({ location: { protocol: "file:" } });
  const { urls, safePath } = vm.runInContext(`${loader}\n({urls: RADAR_URLS, safePath: radarPreferencePath});`, context);
  const readJson = async (url) => JSON.parse(await readFile(resolve(projectRoot, url), "utf8"));
  const entries = [];
  let legacy;
  let index;
  try { index = await readJson(urls.preferences); }
  catch (error) {
    if (error.code !== "ENOENT") throw error;
    // Migration only. The main HTTP route never requests this large legacy file.
    legacy = await readJson("data/radar/journal_preferences.json").catch((failure) => {
      if (failure.code === "ENOENT") return [];
      throw failure;
    });
    index = { schema_version: 1, journals: Object.fromEntries(legacy.map((record) => [record.journal_id, {
      path: `journal_preferences/${record.journal_id}.json`,
      sample_count: record.slices?.all?.sample_count || 0,
      available_time_slices: Object.keys(record.slices || {}),
    }])) };
  }
  for (const url of Object.values(urls)) {
    if (url === urls.preferences) entries.push([url, index]);
    else if (url === urls.manifest) {
      const manifest = await readJson(url).catch((error) => {
        if (error.code === "ENOENT") return { schema_version: 1, data_version: "legacy-preview" };
        throw error;
      });
      entries.push([url, manifest]);
    } else entries.push([url, await readJson(url)]);
  }
  const legacyById = new Map((legacy || []).map((record) => [record.journal_id, record]));
  for (const [id, entry] of Object.entries(index.journals || {})) {
    const url = safePath(entry.path);
    const record = legacyById.get(id) || await readJson(url);
    if (record.journal_id !== id) throw new Error(`Preference journal mismatch: ${id}`);
    const outputPath = resolve(projectRoot, url.replace(/\.json$/, ".js"));
    await mkdir(dirname(outputPath), { recursive: true });
    await writeFile(outputPath, `// Generated offline preference shard.\nglobalThis.__registerRadarPreference(${JSON.stringify(id)}, JSON.parse(${jsonLiteral(record)}));\n`);
  }
  // Only the allowlisted summary datasets enter the initial offline download.
  await writeFile(resolve(projectRoot, "data/radar/local-data.js"), `// Generated by scripts/build-local-data.mjs.\nglobalThis.__radarLocalData = JSON.parse(${jsonLiteral(Object.fromEntries(entries))});\n`);
  if (!quiet) console.log(`Local preview prepared (${entries.length} summary datasets; ${Object.keys(index.journals || {}).length} on-demand preference shards).`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await buildLocalData();
