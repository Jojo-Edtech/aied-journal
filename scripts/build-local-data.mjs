import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const root = fileURLToPath(new URL("../", import.meta.url));

export async function buildLocalData() {
  const loader = await readFile(resolve(root, "data-loader.js"), "utf8");
  const urls = vm.runInNewContext(`${loader}\nObject.values(RADAR_URLS);`, { location: { protocol: "file:" } });
  const entries = await Promise.all(urls.map(async (url) => [
    url,
    JSON.parse(await readFile(resolve(root, url), "utf8")),
  ]));
  // Only the public files requested by the frontend are included, never server files.
  const json = JSON.stringify(Object.fromEntries(entries));
  const literal = JSON.stringify(json).replaceAll("<", "\\u003c").replaceAll("\u2028", "\\u2028").replaceAll("\u2029", "\\u2029");
  await writeFile(resolve(root, "data/radar/local-data.js"), `// Generated by scripts/build-local-data.mjs.\nglobalThis.__radarLocalData = JSON.parse(${literal});\n`);
  console.log(`Local preview data prepared (${entries.length} public datasets).`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  await buildLocalData();
}
